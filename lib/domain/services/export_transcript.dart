/// Version of `transcript.json`. A re-import skips a newer one.
const transcriptJsonSchemaVersion = 1;

/// The label every exported transcript carries (FR-TRN-05, FR-TRN-08).
const transcriptMachineLabel =
    'Machine-generated by speech recognition on the owner\'s device. It may '
    'contain errors and is not a verified record of what was said.';

/// One transcript line as exported.
class ExportTranscriptLine {
  const ExportTranscriptLine({
    required this.index,
    required this.activityStartMs,
    required this.activityEndMs,
    required this.machineText,
    required this.text,
    this.audioStartMs,
    this.audioEndMs,
    this.inCut = false,
  });

  /// The span's index in the saved transcript.
  final int index;

  /// Times on the activity timeline (9.4 rule).
  final int activityStartMs;
  final int activityEndMs;

  /// Position in the part's exported audio file; null when the part has no
  /// audio in this export.
  final int? audioStartMs;
  final int? audioEndMs;

  /// The original machine output, never changed.
  final String machineText;

  /// What the owner reads: their correction, else the machine text.
  final String text;

  /// The line touches a part marked to skip. Only in exports of original
  /// audio, which still hold that speech.
  final bool inCut;

  bool get corrected => text != machineText;
}

/// The lines of one recording segment.
class ExportTranscriptPart {
  const ExportTranscriptPart({
    required this.segmentId,
    required this.sequence,
    required this.segmentStartMs,
    required this.segmentEndMs,
    required this.lines,
    required this.removed,
    required this.createdAt,
    this.audioFile,
    this.trimmed = false,
    this.modelId,
  });

  final String segmentId;
  final int sequence;

  /// The segment on the activity timeline.
  final int segmentStartMs;
  final int segmentEndMs;

  /// The exported audio file, relative to the activity folder, or null
  /// when this export has no audio for the segment.
  final String? audioFile;

  /// The file is a trimmed copy, so its times are shifted.
  final bool trimmed;
  final String? modelId;
  final DateTime createdAt;
  final List<ExportTranscriptLine> lines;

  /// Lines left out because they touch cut or trimmed-out audio, or fall
  /// outside the recording.
  final int removed;
}

/// An activity's transcript as exported.
class ExportTranscript {
  const ExportTranscript({
    required this.audioMode,
    required this.parts,
    required this.cuts,
    required this.gaps,
  });

  final ExportAudioMode audioMode;

  /// In activity timeline order.
  final List<ExportTranscriptPart> parts;

  /// Merged parts marked to skip, on the activity timeline.
  final List<TimeRange> cuts;

  /// Gaps between recordings, on the activity timeline.
  final List<TimeRange> gaps;

  int get lineCount => parts.fold(0, (n, part) => n + part.lines.length);
  int get removedCount => parts.fold(0, (n, part) => n + part.removed);
  int get correctedCount => parts.fold(
    0,
    (n, part) => n + part.lines.where((line) => line.corrected).length,
  );

  /// Lines that are in the exported text even though they touch a cut
  /// (original audio only).
  bool get keepsCutText =>
      audioMode == ExportAudioMode.original ||
      audioMode == ExportAudioMode.originalWithCuts;
}

/// Places [documents] (saved transcripts) on the activity timeline and in
/// the exported audio described by [files] (FR-TRN-08). Null when none of
/// them belongs to one of [segments]: a transcript of a recording that a
/// permanent trim or split replaced counts from audio that no longer
/// exists, so it is not exported.
ExportTranscript? buildExportTranscript({
  required List<RecordingSegment> segments,
  required List<CutRange> cuts,
  required ActivityExportFiles files,
  required ExportAudioMode audioMode,
  required List<TranscriptDocument> documents,
}) {
  final byId = {for (final d in documents) d.segmentId: d};
  final timeline = ReviewTimeline.build(segments: segments);
  final merged = CutRangeMath.mergeOverlappingCutRanges(cuts);
  final parts = <ExportTranscriptPart>[];
  for (final ts in timeline.segments) {
    final document = byId[ts.segment.id];
    if (document == null) continue;
    final segmentId = ts.segment.id;
    final file = audioMode == ExportAudioMode.none
        ? null
        : files.segmentFiles[segmentId];
    final keep = files.trimmedKeepRanges[segmentId];
    final lines = <ExportTranscriptLine>[];
    var removed = 0;
    for (var i = 0; i < document.machineSpans.length; i++) {
      final span = document.machineSpans[i];
      final start = span.start.inMilliseconds;
      final end = span.end.inMilliseconds;
      // Beyond the recording (it was shortened after transcription).
      if (ts.durationMs > 0 && start >= ts.durationMs) {
        removed++;
        continue;
      }
      final activityStart = ts.startMs + start;
      final activityEnd = ts.startMs + end;
      // A zero-length span still marks a moment.
      final touch = TimeRange(
        activityStart,
        activityEnd > activityStart ? activityEnd : activityStart + 1,
      );
      final touchesCut = merged.any(touch.overlaps);
      int? audioStart;
      int? audioEnd;
      switch (audioMode) {
        case ExportAudioMode.trimmed:
          // Cut speech never reappears as text: a line that touches a cut,
          // or audio the copy left out, is removed (ADR-077).
          if (touchesCut) {
            removed++;
            continue;
          }
          if (file != null && keep != null) {
            final position = positionInKeptAudio(keep, start);
            if (position == null || end > position.$2.endMs) {
              removed++;
              continue;
            }
            audioStart = position.$1;
            audioEnd = position.$1 + (end - start);
          } else if (file != null) {
            audioStart = start;
            audioEnd = end;
          } else if (files.segmentNotes[segmentId] == 'cut') {
            removed++;
            continue;
          }
        case ExportAudioMode.none:
          if (touchesCut) {
            removed++;
            continue;
          }
        case ExportAudioMode.original:
        case ExportAudioMode.originalWithCuts:
          if (file != null) {
            audioStart = start;
            audioEnd = end;
          }
      }
      lines.add(
        ExportTranscriptLine(
          index: i,
          activityStartMs: activityStart,
          activityEndMs: activityEnd,
          audioStartMs: audioStart,
          audioEndMs: audioEnd,
          machineText: document.textAt(i, useCorrections: false),
          text: document.textAt(i),
          inCut:
              touchesCut &&
              (audioMode == ExportAudioMode.original ||
                  audioMode == ExportAudioMode.originalWithCuts),
        ),
      );
    }
    parts.add(
      ExportTranscriptPart(
        segmentId: segmentId,
        sequence: ts.segment.sequence,
        segmentStartMs: ts.startMs,
        segmentEndMs: ts.endMs,
        audioFile: file,
        trimmed: file != null && keep != null,
        modelId: document.modelId,
        createdAt: document.createdAt,
        lines: lines,
        removed: removed,
      ),
    );
  }
  if (parts.isEmpty) return null;
  return ExportTranscript(
    audioMode: audioMode,
    parts: parts,
    cuts: merged,
    gaps: [for (final g in timeline.gaps) TimeRange(g.startMs, g.endMs)],
  );
}

/// `hh:mm:ss`, hours always shown.
String formatTranscriptTime(int ms) {
  String two(int v) => v.toString().padLeft(2, '0');
  final s = (ms < 0 ? 0 : ms) ~/ 1000;
  return '${two(s ~/ 3600)}:${two(s ~/ 60 % 60)}:${two(s % 60)}';
}

String _removedWords(int n) =>
    '$n ${n == 1 ? 'line' : 'lines'} removed: the audio was cut or is not '
    'in the recording';

/// `transcript.txt`: UTF-8 plain text with CRLF line ends, so Notepad and
/// every other editor show it as written (FR-TRN-08). The owner's
/// corrected text, one line per span, parts separated by a blank line.
String buildTranscriptText(String title, ExportTranscript transcript) {
  final lines = <String>[
    'Transcript: $title',
    transcriptMachineLabel,
    'Lines the owner corrected show the corrected text. transcript.md has '
        'the times and the original machine text.',
  ];
  for (final part in transcript.parts) {
    lines.add('');
    for (final line in part.lines) {
      lines.add(line.text.replaceAll('\r\n', '\n').replaceAll('\r', '\n'));
    }
    if (part.removed > 0) lines.add('[${_removedWords(part.removed)}]');
  }
  return '${lines.join('\n').replaceAll('\n', '\r\n')}\r\n';
}

/// `transcript.md`: the transcript with times that match the exported
/// audio, the parts, gaps and cuts, and the original machine text under
/// each corrected line (FR-TRN-08).
String buildTranscriptMarkdown(
  String title,
  ExportTranscript transcript, {
  required String timezone,
}) {
  final mode = transcript.audioMode;
  final out = StringBuffer()
    ..writeln('# Transcript: ${escapeTranscriptMarkdown(title)}')
    ..writeln()
    ..writeln(
      '> $transcriptMachineLabel Lines marked *(corrected)* were '
      'edited by the owner; the original machine text is shown under '
      'them.',
    )
    ..writeln()
    ..writeln('## How to read the times')
    ..writeln();
  if (mode == ExportAudioMode.none) {
    out.writeln(
      '- This export has no audio. Each time is the time since the '
      'activity\'s first recording started, counting pauses and gaps, the '
      'same as `offset_seconds` in `timeline.csv`.',
    );
  } else {
    out
      ..writeln(
        '- `[hh:mm:ss - hh:mm:ss]` is the position in the audio file named '
        'in the part\'s heading.',
      )
      ..writeln(
        '- *activity* is the time since the activity\'s first recording '
        'started, counting pauses and gaps, the same as `offset_seconds` '
        'in `timeline.csv`.',
      );
  }
  if (mode == ExportAudioMode.trimmed) {
    out.writeln(
      '- The audio files are trimmed copies: lines that touched a cut part '
      'were removed and later times are shifted to match the files.',
    );
  } else if (mode == ExportAudioMode.none && transcript.cuts.isNotEmpty) {
    out.writeln('- Lines that touched a part cut from the audio were removed.');
  }
  if (transcript.keepsCutText && transcript.cuts.isNotEmpty) {
    out.writeln(
      '- This export has the original audio, which still holds the parts '
      'marked to skip, so their lines are kept with their original times '
      'and marked *(in a part marked to skip)*. Parts marked to skip '
      '(activity times): '
      '${[for (final c in transcript.cuts) '${formatTranscriptTime(c.startMs)} to ${formatTranscriptTime(c.endMs)}'].join('; ')}.',
    );
  }
  out.writeln(
    '- Times are hours:minutes:seconds from the start of the file or the '
    'activity, not clock times. `activity.md` has the clock times '
    '($timezone).',
  );

  var lastEnd = 0;
  var first = true;
  for (final part in transcript.parts) {
    for (final gap in transcript.gaps) {
      if (!first &&
          gap.startMs >= lastEnd &&
          gap.endMs <= part.segmentStartMs) {
        out
          ..writeln()
          ..writeln(
            '*Gap: nothing recorded from activity '
            '${formatTranscriptTime(gap.startMs)} to '
            '${formatTranscriptTime(gap.endMs)}.*',
          );
      }
    }
    first = false;
    lastEnd = part.segmentEndMs;
    out
      ..writeln()
      ..writeln(
        part.audioFile == null
            ? '## Part ${part.sequence} (audio not in this export)'
            : '## Part ${part.sequence}: `${part.audioFile}`'
                  '${part.trimmed ? ' (trimmed copy)' : ''}',
      )
      ..writeln()
      ..writeln(
        'Activity ${formatTranscriptTime(part.segmentStartMs)} to '
        '${formatTranscriptTime(part.segmentEndMs)}.',
      )
      ..writeln();
    if (part.lines.isEmpty) out.writeln('No transcript text in this part.');
    for (final line in part.lines) {
      final when = line.audioStartMs == null
          ? '**[${formatTranscriptTime(line.activityStartMs)} - '
                '${formatTranscriptTime(line.activityEndMs)}]**'
          : '**[${formatTranscriptTime(line.audioStartMs!)} - '
                '${formatTranscriptTime(line.audioEndMs!)}]** '
                '(activity ${formatTranscriptTime(line.activityStartMs)})';
      final flags = [
        if (line.corrected) '*(corrected)*',
        if (line.inCut) '*(in a part marked to skip)*',
      ].join(' ');
      out.writeln(
        '- $when ${escapeTranscriptMarkdown(line.text)}'
        '${flags.isEmpty ? '' : ' $flags'}',
      );
      if (line.corrected) {
        out.writeln(
          '  - Original machine text: '
          '${escapeTranscriptMarkdown(line.machineText)}',
        );
      }
    }
    if (part.removed > 0) {
      out
        ..writeln()
        ..writeln('*${_removedWords(part.removed)}.*');
    }
  }
  return out.toString();
}

const _json = JsonEncoder.withIndent('  ');

/// `transcript.json`: the same for software and for re-import (ADR-049,
/// ADR-077). `audio_file` is relative to the activity folder, like
/// `activity.json` and `cuts.json`; `audio_start_ms` and `audio_end_ms`
/// are positions in that file, so a re-import can attach the lines to the
/// imported recording. Removed lines are counted, never listed.
String buildTranscriptJson(String activityId, ExportTranscript transcript) {
  final map = <String, Object?>{
    'schema_version': transcriptJsonSchemaVersion,
    'kind': 'attenlume_transcript',
    'machine_generated': true,
    'label': transcriptMachineLabel,
    'activity_id': activityId,
    'audio_mode': transcript.audioMode.key,
    'line_count': transcript.lineCount,
    'corrected_count': transcript.correctedCount,
    'removed_count': transcript.removedCount,
    'cuts': [for (final c in transcript.cuts) c.toJson()],
    'gaps': [for (final g in transcript.gaps) g.toJson()],
    'parts': [
      for (final part in transcript.parts)
        {
          'segment_id': part.segmentId,
          'sequence': part.sequence,
          'audio_file': part.audioFile,
          'trimmed': part.trimmed,
          'segment_start_ms': part.segmentStartMs,
          'segment_end_ms': part.segmentEndMs,
          'model_id': part.modelId,
          'created_at_utc': part.createdAt.toUtc().toIso8601String(),
          'removed_count': part.removed,
          'lines': [
            for (final line in part.lines)
              {
                'index': line.index,
                'activity_start_ms': line.activityStartMs,
                'activity_end_ms': line.activityEndMs,
                'audio_start_ms': line.audioStartMs,
                'audio_end_ms': line.audioEndMs,
                'machine_text': line.machineText,
                'text': line.text,
                'corrected': line.corrected,
                'in_cut': line.inCut,
              },
          ],
        },
    ],
  };
  return '${_json.convert(map)}\n';
}
