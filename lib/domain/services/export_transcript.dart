/// Saved transcripts in conference exports, aligned with the exported
/// audio (FR-TRN-08, FR-TRN-09, ADR-077) [P2-09].
///
/// A saved transcript belongs to one recording segment and its times count
/// from the start of that segment's audio (`TranscriptDocument`). Here
/// each line is placed twice: on the activity timeline (the 9.4 rule:
/// time since the first recording started, gaps counted, the same as
/// `offset_seconds` in `timeline.csv`), and in the exported audio file
/// that holds it, so the times match what the export actually contains:
///
/// - **Original audio** (with or without `cuts.json`): every line keeps
///   its original time. Lines that touch a part marked to skip are kept
///   (the audio still holds that speech) and flagged.
/// - **Trimmed copies:** a line that touches a cut, or audio the trimmed
///   copy left out, is removed, and later times are shifted through the
///   copy's kept ranges, the same ranges the trimmer used
///   ([positionInKeptAudio]). Cut speech never reappears as text.
/// - **No audio** (notes and details only): lines that touch a cut are
///   removed, as for trimmed copies; times are activity times only.
///
/// The owner's corrections are the text; the original machine output stays
/// available in `transcript.md` (under each corrected line) and in
/// `transcript.json`, which also lets a re-import restore the transcript
/// (ADR-049).
